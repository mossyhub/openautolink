def test_safe_extraction_preserves_files_and_rejects_escape(tmp_path):
    good = tmp_path / 'good.zip'
    with zipfile.ZipFile(good, 'w') as z:
        z.writestr('root/bin/tool', b'hello')
    tc.safe_extract(good, tmp_path / 'out', strip_root=True)
    assert (tmp_path / 'out/bin/tool').read_bytes() == b'hello'
    for name in ['../escape', '/absolute', 'C:/drive', 'root/../../escape', 'root\\evil']:
        bad = tmp_path / 'bad.zip'
        with zipfile.ZipFile(bad, 'w') as z:
            z.writestr(name, b'bad')
        with pytest.raises(tc.BuilderError, match='archive'):
            tc.safe_extract(bad, tmp_path / 'reject')
    assert not (tmp_path / 'escape').exists()


def test_sdk_metadata_selects_pinned_os_and_checksums():
    xml = b'''<repository><license id="android-sdk-license">Terms</license>
    <remotePackage path="cmake;3.22.1"><uses-license ref="android-sdk-license"/>
    <archives><archive><host-os>linux</host-os><complete><size>3</size>
    <checksum type="sha1">a9993e364706816aba3e25717850c26c9cd0d89d</checksum>
    <url>cmake.zip</url></complete></archive></archives></remotePackage></repository>'''
    package = tc.sdk_package(xml, 'cmake;3.22.1', 'linux')
    assert package['url'] == 'https://dl.google.com/android/repository/cmake.zip'
    assert package['algorithm'] == 'sha1'
    assert package['license'] == ('android-sdk-license', 'Terms')
    with pytest.raises(tc.BuilderError, match='available'):
        tc.sdk_package(xml, 'cmake;3.22.1', 'windows')


def test_download_verifies_cached_bytes_and_rejects_corruption(tmp_path, monkeypatch):
    import hashlib
    import threading
    payload = b'actual response bytes'
    class Response(io.BytesIO):
        def geturl(self):
            return 'https://dl.google.com/tool.zip'
    requests = []
    def open_url(request, timeout):
        requests.append(request.full_url)
        return Response(payload)
    monkeypatch.setattr(tc.urllib.request, 'urlopen', open_url)
    dl = tc.Downloader(tmp_path, lambda *_: None, threading.Event())
    digest = hashlib.sha256(payload).hexdigest()
    result = dl.download('https://dl.google.com/tool.zip', digest)
    assert result.read_bytes() == payload
    assert dl.download('https://dl.google.com/tool.zip', digest) == result
    assert len(requests) == 1
    result.write_bytes(b'corrupt cache')
    assert dl.download('https://dl.google.com/tool.zip', digest).read_bytes() == payload
    with pytest.raises(tc.BuilderError, match='checksum'):
        dl.download('https://dl.google.com/tool.zip', '0' * 64)
    with pytest.raises(tc.BuilderError, match='HTTPS'):
        dl.download('http://dl.google.com/tool.zip', digest)


@pytest.mark.parametrize(('release_tag', 'commit'), [('v1.2.3', 'a' * 40), ('v0.1.526', '580a68d772afc97e444019504178f1678731feb6')])
def test_source_release_is_commit_bound_and_native_gitlink_checked(tmp_path, release_tag, commit):
    import hashlib
    import threading
    gitlink = 'b' * 40
    source = tmp_path / 'source.zip'
    with zipfile.ZipFile(source, 'w') as z:
        z.writestr('repo/app/src/main/cpp/CMakeLists.txt', 'AASDK_SOURCE_DIR external/opencardev-aasdk')
        z.writestr('repo/gradlew', 'wrapper')
        z.writestr('repo/gradle/verification-metadata.xml', native_verification_fixture())
        z.writestr('repo/app/src/main/AndroidManifest.xml', '<manifest><activity android:name="androidx.car.app.activity.CarAppActivity" android:taskAffinity="com.openautolink.app.templates"/></manifest>')
    headers = tmp_path / 'headers.zip'
    with zipfile.ZipFile(headers, 'w') as z:
        z.writestr('aasdk/include/aasdk/header.h', 'headers')
    assets = []
    archives = {}
    for abi in ('arm64-v8a', 'x86_64'):
        archive = tmp_path / (abi + '.tar.gz')
        with tarfile.open(archive, 'w:gz') as t:
            content = b'archive fixture'
            info = tarfile.TarInfo('third_party/aasdk/' + abi + '/lib/libaasdk.a')
            info.size = len(content)
            t.addfile(info, io.BytesIO(content))
        digest = hashlib.sha256(archive.read_bytes()).hexdigest()
        assets.append({'name': 'native-deps-' + abi + '.tar.gz', 'digest': 'sha256:' + digest, 'browser_download_url': 'https://github.com/' + abi})
        archives[digest] = archive
    class Network:
        def json(self, url):
            if url.endswith('/releases/latest'):
                return {'tag_name': release_tag, 'prerelease': False, 'draft': False}
            if '/commits/' in url:
                return {'sha': commit}
            if '/git/trees/' in url:
                return {'tree': [{'path': 'external/opencardev-aasdk', 'mode': '160000', 'sha': gitlink}], 'truncated': False}
            return {'body': 'aasdk ' + gitlink, 'assets': assets}
        def download(self, url, digest=None, **kw):
            if digest:
                return archives[digest]
            assert commit in url or gitlink in url
            return headers if 'mossyhub/aasdk' in url else source
        def check_cancel(self):
            pass
    manager = tc.Toolchain(tmp_path / 'work', lambda *_: None, threading.Event())
    manager.downloader = Network()
    result = manager.prepare_source()
    assert result['sourceCommit'] == commit
    assert result['versionName'] == release_tag.removeprefix('v')
    native_overlays = ['native-gradle-verification-v0.1.526'] if release_tag == 'v0.1.526' else []
    assert result['sourceOverlays'] == ['personal-cluster-task-affinity', *native_overlays]
    if native_overlays:
        assert 'protoc-4.29.3-osx-aarch_64.exe' in (tmp_path / 'work/source/gradle/verification-metadata.xml').read_text()
    assert (tmp_path / 'work/source/external/opencardev-aasdk/include/aasdk/header.h').is_file()
    assert (tmp_path / 'work/source/app/src/main/cpp/third_party/aasdk/arm64-v8a/lib/libaasdk.a').is_file()
    assets[0]['digest'] = None
    with pytest.raises(tc.BuilderError, match='SHA-256'):
        manager.prepare_source()


def test_tool_install_consent_and_child_only_environment(tmp_path, monkeypatch):
    import threading
    manager = tc.Toolchain(tmp_path, lambda *_: None, threading.Event())
    with pytest.raises(tc.BuilderError, match='license'):
        manager.install(False)
    monkeypatch.setenv('UPLOAD_STORE_PASSWORD', 'must-not-be-inherited')
    monkeypatch.setenv('JAVA_TOOL_OPTIONS', '-javaagent:untrusted')
    env = manager.environment(tmp_path / 'tools/jdk')
    assert 'UPLOAD_STORE_PASSWORD' not in env and 'JAVA_TOOL_OPTIONS' not in env
    assert env['GRADLE_USER_HOME'] == str(tmp_path / 'cache/gradle')
    assert env['JAVA_HOME'] == str(tmp_path / 'tools/jdk')
    assert env['CMAKE_BUILD_PARALLEL_LEVEL'] == '2'
    assert os.environ['JAVA_TOOL_OPTIONS'] == '-javaagent:untrusted'


def test_manifest_overlay_is_only_cluster_affinity(tmp_path):
    manifest = tmp_path / 'AndroidManifest.xml'
    original = '''<manifest xmlns:android="http://schemas.android.com/apk/res/android"><application>
    <activity android:name="some.Other" android:taskAffinity="com.openautolink.app.templates"/>
    <activity android:name="androidx.car.app.activity.CarAppActivity" android:taskAffinity="com.openautolink.app.templates"/>
    </application></manifest>'''
    manifest.write_text(original)
    assert tc.personalize_cluster_affinity(manifest)
    changed = manifest.read_text()
    assert '<activity android:name="some.Other" android:taskAffinity="com.openautolink.app.templates"/>' in changed
    assert '<activity android:name="androidx.car.app.activity.CarAppActivity" android:taskAffinity="${applicationId}.templates"/>' in changed
    assert not tc.personalize_cluster_affinity(manifest)


def test_archive_links_never_escape_and_contained_tool_links_work(tmp_path):
    archive = tmp_path / 'tools.tar.gz'
    with tarfile.open(archive, 'w:gz') as t:
        file = tarfile.TarInfo('root/bin/java')
        file.size = 4
        file.mode = 0o755
        t.addfile(file, io.BytesIO(b'tool'))
        link = tarfile.TarInfo('root/bin/javac')
        link.type = tarfile.SYMTYPE
        link.linkname = 'java'
        t.addfile(link)
    tc.safe_extract(archive, tmp_path / 'jdk', strip_root=True, allow_links=True)
    assert (tmp_path / 'jdk/bin/javac').read_bytes() == b'tool'
    with pytest.raises(tc.BuilderError, match='Links'):
        tc.safe_extract(archive, tmp_path / 'reject')
