def test_native_verification_overlay_adds_exact_pinned_classifiers(tmp_path):
    import xml.etree.ElementTree as ET
    metadata = tmp_path / 'gradle/verification-metadata.xml'
    metadata.parent.mkdir()
    original = native_verification_fixture()
    metadata.write_text(original)
    result = tc.apply_native_verification_overlay(tmp_path, 'v0.1.526', '580a68d772afc97e444019504178f1678731feb6')
    assert result == ['native-gradle-verification-v0.1.526']
    root = ET.fromstring(metadata.read_bytes())
    ns = {'v': 'https://schema.gradle.org/dependency-verification'}
    expected = {
        'aapt2-8.7.3-12006047-windows.jar': '9406af8e4742da01e4ce65773e23bda40ed5f599917b38cacc261c9ba0952331',
        'aapt2-8.7.3-12006047-osx.jar': '8cfca8d3fcb8ad45cf46e3780cdd4a64cb38c70ca45b442655de9f3e7d19efc1',
        'protoc-4.29.3-windows-x86_64.exe': 'daea6bfd3d3304665835c694ceeab304e4e0c3ee52d653428fdcde3b6e4d19e1',
        'protoc-4.29.3-osx-x86_64.exe': '461e34e09b392b7f5ce6696b1b5387112ac56ccc44088c599dc430905fa35e47',
        'protoc-4.29.3-osx-aarch_64.exe': 'bdc43e54153911f625a50baf7d4f6bc05008712964141baedd5a61122f93a016',
    }
    artifacts = {a.get('name'): a.find('v:sha256', ns).get('value') for a in root.findall('v:components/v:component/v:artifact', ns)}
    assert {k: v for k, v in artifacts.items() if k in expected} == expected
    assert len(artifacts) == 9
    # No broad trust entries, existing checksum changes, or settings changes.
    assert not root.findall('.//v:trusted-artifacts', ns)
    for old in ET.fromstring(original).findall('v:components/v:component/v:artifact', ns):
        assert artifacts[old.get('name')] == old.find('v:sha256', ns).get('value')
    assert root.find('v:configuration/v:verify-metadata', ns).text == 'true'


@pytest.mark.parametrize(('tag', 'commit', 'error'), [
    ('v0.1.527', 'a' * 40, False),
    ('v0.1.526', 'a' * 40, True),
])
def test_native_verification_overlay_never_trusts_another_release(tmp_path, tag, commit, error):
    metadata = tmp_path / 'gradle/verification-metadata.xml'
    metadata.parent.mkdir()
    metadata.write_text(native_verification_fixture())
    before = metadata.read_bytes()
    if error:
        with pytest.raises(tc.BuilderError, match='verification overlay'):
            tc.apply_native_verification_overlay(tmp_path, tag, commit)
    else:
        assert tc.apply_native_verification_overlay(tmp_path, tag, commit) == []
    assert metadata.read_bytes() == before


@pytest.mark.parametrize('mutation', ['version', 'malformed', 'duplicate', 'conflict'])
def test_native_verification_overlay_fails_closed_without_partial_write(tmp_path, mutation):
    metadata = tmp_path / 'gradle/verification-metadata.xml'
    metadata.parent.mkdir()
    text = native_verification_fixture()
    if mutation == 'version':
        text = text.replace('4.29.3', '4.29.4')
    elif mutation == 'malformed':
        text = text.replace('</components>', '')
    elif mutation == 'duplicate':
        text = text.replace('</components>', '<component group="com.google.protobuf" name="protoc" version="4.29.3"/></components>')
    else:
        text = text.replace('<artifact name="protoc-4.29.3.pom">', '<artifact name="protoc-4.29.3-osx-x86_64.exe">')
    metadata.write_text(text)
    with pytest.raises(tc.BuilderError, match='verification overlay'):
        tc.apply_native_verification_overlay(tmp_path, 'v0.1.526', '580a68d772afc97e444019504178f1678731feb6')
    assert metadata.read_text() == text


